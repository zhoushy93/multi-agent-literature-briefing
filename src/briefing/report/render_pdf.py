"""S8 Renderer: ``Briefing`` -> HTML -> PDF.

WeasyPrint is the primary engine because it supports the paged-media features
AGENTS.md §8 requires: running page numbers and a table of contents whose
entries carry page numbers (``target-counter``). Chromium cannot do the latter,
so it is only the fallback, and using it sets ``fallback = True`` on the result
so the manifest can never hide the switch.

macOS note (docs/decisions/001-runtime-and-renderer.md): WeasyPrint reaches
Homebrew's Pango through dyld, so ``DYLD_FALLBACK_LIBRARY_PATH`` has to be set
*before* ``weasyprint`` is imported. That is why the import happens inside a
function rather than at module scope.
"""

