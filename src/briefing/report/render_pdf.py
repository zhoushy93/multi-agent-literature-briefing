@dataclass(frozen=True)
class ReportContext:
    """Everything the template needs, gathered by the orchestrator (Step 13)."""

    briefing: Briefing
    selected: SelectedPapers
    search_plan: SearchPlan | None = None
    model_id: str = "unknown"
    prompt_versions: dict[str, str] = field(default_factory=dict)
    llm_calls: int = 0
    total_tokens: int = 0
    generated_at: datetime | None = None


@dataclass(frozen=True)
class PdfCheck:
    """What was verified about a produced PDF."""

    ok: bool
    page_count: int
    text_extractable: bool
    fonts_embedded: bool
    cjk_present: bool
    problem: str = ""


@dataclass(frozen=True)
class RenderResult:
    """Auditable outcome of a render, surfaced in ``manifest.json``."""

    pdf_path: Path
    html_path: Path
    renderer: str
    fallback: bool
    page_count: int
    fonts_embedded: bool


class PdfEngine(Protocol):
    name: str

    def render(self, html: str, target: Path, *, html_path: Path) -> None: ...


def _prepare_library_path() -> None:
    """Point dyld at Homebrew's libraries before WeasyPrint is imported."""
    if sys.platform != "darwin":
        return
    if Path(HOMEBREW_LIB).is_dir():
        os.environ.setdefault("DYLD_FALLBACK_LIBRARY_PATH", HOMEBREW_LIB)


def _load_weasyprint() -> Any:
    """Import WeasyPrint only after the library path has been repaired."""
    _prepare_library_path()
    from weasyprint import HTML

    return HTML


class WeasyPrintEngine:
    """Primary engine: full paged-media support, runs in-process."""

    name = "weasyprint"

    def render(self, html: str, target: Path, *, html_path: Path) -> None:
        document = _load_weasyprint()(string=html, base_url=str(html_path.parent))
        document.write_pdf(str(target))


class ChromiumEngine:
    """Fallback engine: headless Chrome printing the same HTML file."""

    name = "chromium"

    def __init__(self, binary: Path | None = None) -> None:
        self._binary = binary

    @property
    def binary(self) -> Path | None:
        if self._binary is not None:
            return self._binary
        for candidate in CHROME_CANDIDATES:
            if Path(candidate).is_file():
                return Path(candidate)
        return None

    def render(self, html: str, target: Path, *, html_path: Path) -> None:
        binary = self.binary
        if binary is None:
            raise RenderError("no chromium binary found for the fallback renderer")
        # A fixed argv list, no shell, no user-controlled command.
        completed = subprocess.run(
            [
                str(binary),
                "--headless",
                "--disable-gpu",
                "--no-sandbox",
                f"--print-to-pdf={target}",
                html_path.as_uri(),
            ],
            capture_output=True,
            check=False,
        )
        if completed.returncode != 0 or not target.is_file():
            detail = completed.stderr.decode("utf-8", "replace")[-300:]
            raise RenderError(f"chromium exited with {completed.returncode}: {detail}")


def default_engines() -> list[PdfEngine]:
    return [WeasyPrintEngine(), ChromiumEngine()]


def render_report(
    context: ReportContext,
    out_dir: Path,
    *,
    engines: Sequence[PdfEngine] | None = None,
) -> RenderResult:
    """Render the briefing, falling back through the engine list in order."""
    out_dir.mkdir(parents=True, exist_ok=True)
    stage_dir = out_dir / "_stages"
    stage_dir.mkdir(parents=True, exist_ok=True)

    html = render_html(context)
    html_path = stage_dir / STAGE_HTML_PATH
    html_path.write_text(html, encoding="utf-8")
    pdf_path = out_dir / "report.pdf"

    failures: list[str] = []
    for position, engine in enumerate(engines or default_engines()):
        try:
            engine.render(html, pdf_path, html_path=html_path)
        except Exception as exc:
            failures.append(f"{engine.name}: {exc}")
            logger.warning(
                "pdf engine failed",
                extra={"engine": engine.name, "reason": str(exc)},
            )
            continue

        check = verify_pdf(pdf_path, expect_cjk=context.briefing.lang == "zh")
        if not check.ok:
            failures.append(f"{engine.name}: {check.problem}")
            logger.warning(
                "pdf failed verification",
                extra={"engine": engine.name, "reason": check.problem},
            )
            continue

        return RenderResult(
            pdf_path=pdf_path,
            html_path=html_path,
            renderer=engine.name,
            fallback=position > 0,
            page_count=check.page_count,
            fonts_embedded=check.fonts_embedded,
        )

    raise RenderError("no pdf engine produced a usable report: " + "; ".join(failures))


# --- html ---------------------------------------------------------------------


def render_html(context: ReportContext) -> str:
    briefing = context.briefing
    labels = LABELS[briefing.lang]
    mapping = build_reference_map(context.selected)
    references = build_references(context.selected)
    generated_at = context.generated_at or datetime.now(UTC)

    cards: list[dict[str, Any]] = []
    for position, (card, screened) in enumerate(
        zip(briefing.paper_cards, context.selected.items, strict=True),
        start=1,
    ):
        paper = screened.paper
        cards.append(
            {
                "number": mapping.get(card.citation_key, position),
                "title": paper.title,
                "authors": format_authors(paper.authors),
                "venue": paper.venue or paper.origin,
                "year": paper.year if paper.year is not None else "n.d.",
                "year_value": paper.year,
                "url": paper.url,
                "problem": card.analysis.problem,
                "method": card.analysis.method,
                "data_and_experiments": card.analysis.data_and_experiments,
                "key_findings": card.analysis.key_findings,
                "limitations": card.analysis.limitations,
                "relevance": card.analysis.relevance,
                "reusable_ideas": card.analysis.reusable_ideas,
                "confidence": card.analysis.confidence,
            }
        )

    comparison: list[dict[str, Any]] = [
        {
            "number": mapping.get(row.citation_key, position),
            "task": row.task,
            "method_family": row.method_family,
            "data": row.data,
            "metrics": row.metrics,
            "main_result": row.main_result,
        }
        for position, row in enumerate(briefing.comparison, start=1)
    ]

    family_by_number = {row["number"]: row["method_family"] for row in comparison}
    summary_rows = [
        {
            "number": card["number"],
            "title": truncate(card["title"], 58),
            "year": card["year"],
            "method_family": truncate(family_by_number.get(card["number"], "—"), 26),
            "finding": truncate(card["key_findings"][0], 130),
            "relevance": truncate(card["relevance"], 190),
        }
        for card in cards
    ]
    topic_overview = render_topic_overview(
        briefing.topic,
        [
            OverviewEntry(
                number=card["number"],
                title=card["title"],
                year=card["year_value"],
                method_family=family_by_number.get(card["number"], ""),
            )
            for card in cards
        ],
    )

    def claims(items: Sequence[Claim]) -> list[dict[str, str]]:
        return [
            {
                "text": claim.text,
                "citations": resolve_claim_keys(claim.citation_keys, mapping),
            }
            for claim in items
        ]

    sections = _sections(labels, has_further_reading=bool(briefing.further_reading))
    plan = context.search_plan

    environment = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        autoescape=select_autoescape(("html", "xml")),
        trim_blocks=True,
        lstrip_blocks=True,
    )
    template = environment.get_template(TEMPLATE_NAME)
    return template.render(
        lang=briefing.lang,
        labels=labels,
        title=f"{briefing.topic} — {labels['title_suffix']}",
        subtitle=labels["subtitle"],
        run_id=briefing.run_id,
        model_id=context.model_id,
        prompt_versions=context.prompt_versions,
        llm_calls=context.llm_calls,
        total_tokens=context.total_tokens,
        generated_at=generated_at.strftime("%Y-%m-%d %H:%M UTC"),
        styles=STYLESHEET.read_text(encoding="utf-8"),
        sections=sections,
        executive_summary=resolve_citations(briefing.executive_summary, mapping),
        background_html=render_markdown(resolve_citations(briefing.background_md, mapping)),
        method_html=render_markdown(resolve_citations(briefing.method_md, mapping)),
        queries=[f"{query.source}: {query.q}" for query in (plan.queries if plan else [])],
        inclusion_criteria=list(plan.inclusion_criteria) if plan else [],
        exclusion_criteria=list(plan.exclusion_criteria) if plan else [],
        cards=cards,
        summary_rows=summary_rows,
        topic_overview=topic_overview,
        comparison=comparison,
        gaps=claims(list(briefing.gaps_and_open_questions)),
        further_reading=claims(list(briefing.further_reading)),
        references=references,
    )


def _sections(labels: dict[str, str], *, has_further_reading: bool) -> list[dict[str, str]]:
    """The fixed chapter list of AGENTS.md §8, in order."""
    sections = [
        {"anchor": "summary", "title": labels["summary"]},
        {"anchor": "overview", "title": labels["overview"]},
        {"anchor": "background", "title": labels["background"]},
        {"anchor": "method", "title": labels["method"]},
        {"anchor": "cards", "title": labels["cards"]},
        {"anchor": "comparison", "title": labels["comparison"]},
        {"anchor": "gaps", "title": labels["gaps"]},
    ]
    if has_further_reading:
        sections.append({"anchor": "further-reading", "title": labels["further_reading"]})
    sections.append({"anchor": "references", "title": labels["references"]})
    sections.append({"anchor": "appendix", "title": labels["appendix"]})
    return sections


# --- pdf verification ---------------------------------------------------------


def verify_pdf(path: Path, *, expect_cjk: bool) -> PdfCheck:
    """Prove the PDF is usable: pages, extractable text, embedded fonts."""
    if not path.is_file() or path.stat().st_size == 0:
        return PdfCheck(False, 0, False, False, False, "the pdf file is empty")

    try:
        reader = PdfReader(str(path))
        page_count = len(reader.pages)
        text = "\n".join(page.extract_text() or "" for page in reader.pages)
        fonts_embedded = _all_fonts_embedded(reader)
    except Exception as exc:
        return PdfCheck(False, 0, False, False, False, f"unreadable pdf: {exc}")

    text_extractable = bool(text.strip())
    cjk_present = contains_cjk(text)

    problem = ""
    if page_count == 0:
        problem = "the pdf has no pages"
    elif not text_extractable:
        problem = "no text could be extracted (rendered as an image?)"
    elif not fonts_embedded:
        problem = "the pdf contains fonts that are not embedded"
    elif expect_cjk and not cjk_present:
        problem = "a Chinese briefing produced no extractable Chinese text"

    return PdfCheck(
        ok=not problem,
        page_count=page_count,
        text_extractable=text_extractable,
        fonts_embedded=fonts_embedded,
        cjk_present=cjk_present,
        problem=problem,
    )


def _all_fonts_embedded(reader: PdfReader) -> bool:
    seen = 0
    embedded = 0
    for page in reader.pages:
        resources = page.get("/Resources") or {}
        fonts = resources.get("/Font") or {}
        for reference in fonts.values():
            font = reference.get_object()
            seen += 1
            if _font_is_embedded(font):
                embedded += 1
    return seen > 0 and seen == embedded


def _font_is_embedded(font: Any) -> bool:
    descriptor = font.get("/FontDescriptor")
    if descriptor is None:
        for descendant in font.get("/DescendantFonts") or []:
            candidate = descendant.get_object().get("/FontDescriptor")
            if candidate is not None:
                descriptor = candidate
                break
    if descriptor is None:
        return False
    return any(key in descriptor for key in ("/FontFile", "/FontFile2", "/FontFile3"))


def chromium_available() -> bool:
    """Whether a fallback engine is installed at all."""
    return ChromiumEngine().binary is not None or shutil.which("chromium") is not None
